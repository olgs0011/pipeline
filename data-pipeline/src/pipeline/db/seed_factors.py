def seed_factors() -> None:
    with session_scope() as session:
        added, updated = 0, 0
        for code, name, unit, category, source_hint in FACTORS:
            existing = session.get(Factor, code)
            if existing is None:
                session.add(Factor(
                    code=code, name=name, unit=unit,
                    category=category, source_hint=source_hint,
                ))
                added += 1
            else:
                changed = (
                    existing.name != name
                    or existing.unit != unit
                    or existing.category != category
                    or existing.source_hint != source_hint
                )
                if changed:
                    existing.name = name
                    existing.unit = unit
                    existing.category = category
                    existing.source_hint = source_hint
                    updated += 1
    logger.success(f"Факторы: добавлено {added}, обновлено {updated}, всего {len(FACTORS)}")


if __name__ == "__main__":
    setup_logging()
    seed_factors()