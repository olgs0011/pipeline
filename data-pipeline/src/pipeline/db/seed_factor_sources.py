def seed_factor_sources() -> None:
    with session_scope() as session:
        session.query(FactorSource).filter_by(source_id=SOURCE_ID).delete()

        added = 0
        for factor_code, (external_id, filter_json, confidence, note) in MANUAL_OVERRIDES.items():
            session.add(
                FactorSource(
                    factor_code=factor_code,
                    source_id=SOURCE_ID,
                    external_id=str(external_id),
                    filter_json=filter_json,
                    match_method="manual",
                    confidence=confidence,
                    notes=note or None,
                )
            )
            added += 1

    logger.success(f"Маппингов залито: {added}")


if __name__ == "__main__":
    setup_logging()
    seed_factor_sources()